#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Visualize density fields generated by the IQC nucleation code.

Examples
--------
Run from the repository root:

    python result/plotphi.py result/S1.txt

Run from the result directory:

    python plotphi.py S1.txt

MATLAB files are still supported:

    python result/plotphi.py result/S1.mat --mat-key x1
"""

import argparse
from pathlib import Path

import numpy as np
import scipy.io as scio
from mayavi import mlab
from scipy.fftpack import fftfreq, fftn


def resolve_input(filename):
    path = Path(filename)
    if path.exists():
        return path

    result_path = Path("result") / filename
    if result_path.exists():
        return result_path

    raise FileNotFoundError(f"Cannot find input file: {filename}")


def infer_grid_size(values):
    n_values = values.size
    n_grid = int(round(n_values ** (1.0 / 3.0)))
    if n_grid ** 3 != n_values:
        raise ValueError(
            f"Input has {n_values} values, which is not a perfect cube."
        )
    return n_grid


def load_density(filename, mat_key):
    path = resolve_input(filename)
    suffix = path.suffix.lower()

    if suffix == ".txt":
        values = np.loadtxt(path)
    elif suffix == ".mat":
        load_data = scio.loadmat(path)
        if mat_key not in load_data:
            keys = sorted(k for k in load_data.keys() if not k.startswith("__"))
            raise KeyError(
                f"Key '{mat_key}' not found in {path}. Available keys: {keys}"
            )
        values = load_data[mat_key]
    else:
        raise ValueError("Supported input formats are .txt and .mat")

    values = np.asarray(values, dtype=float).flatten()
    n_grid = infer_grid_size(values)
    return values.reshape(n_grid, n_grid, n_grid), n_grid, path


def plot_density(U3, N, domain_length):
    xgrids = np.linspace(0, domain_length * 2 * np.pi, N, endpoint=False)
    Y3, X3, Z3 = np.meshgrid(xgrids, xgrids, xgrids)

    mlab.figure(size=(500, 450), bgcolor=(1, 1, 1), fgcolor=(0.0, 0.0, 0.0))
    mlab.contour3d(X3, Y3, Z3, U3, colormap="jet")
    mlab.outline()
    mlab.show()


def plot_fourier_peaks(U3, N, peak_ratio):
    kterm = fftfreq(N, 1 / N)
    data = fftn(U3)
    threshold = np.max(np.abs(data)) / peak_ratio

    w1, w2, w3 = np.where(np.abs(data) > threshold)
    C = np.abs(data[np.abs(data) > threshold])
    X = kterm[w1]
    Y = kterm[w2]
    Z = kterm[w3]

    idx = np.argsort(C)
    C = C[idx]
    X = X[idx]
    Y = Y[idx]
    Z = Z[idx]

    mlab.figure(size=(500, 450), bgcolor=(1, 1, 1), fgcolor=(0.0, 0.0, 0.0))
    mlab.points3d(X, Y, Z, C)
    mlab.show()


def main():
    parser = argparse.ArgumentParser(
        description="Visualize a density field saved by the IQC nucleation code."
    )
    parser.add_argument(
        "input",
        nargs="?",
        default="S1.txt",
        help="Input density file. Supports .txt output from the C++ code or .mat.",
    )
    parser.add_argument(
        "--mat-key",
        default="x1",
        help="Variable name to load when the input is a .mat file.",
    )
    parser.add_argument(
        "--L",
        type=float,
        default=26.0,
        help="Periodic approximation length used for the real-space domain.",
    )
    parser.add_argument(
        "--peak-ratio",
        type=float,
        default=100.0,
        help="Show Fourier peaks larger than max(abs(F))/peak_ratio.",
    )
    parser.add_argument(
        "--density-only",
        action="store_true",
        help="Only plot the real-space density field.",
    )
    args = parser.parse_args()

    U3, N, path = load_density(args.input, args.mat_key)
    print(f"Loaded {path} as a {N} x {N} x {N} density field.")

    plot_density(U3, N, args.L)
    if not args.density_only:
        plot_fourier_peaks(U3, N, args.peak_ratio)


if __name__ == "__main__":
    main()
